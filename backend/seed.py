def run_seed():
    print("Initializing database tables...")
    Base.metadata.create_all(bind=engine)

    with SessionLocal() as db:
        print("Seeding tags and settings...")
        crud.seed_setup_tags(db)
        crud.seed_mistake_tags(db)
        crud.get_settings(db)

        # Clear existing trades if any for clean test
        trade_count = db.query(models.Trade).count()
        if trade_count == 0:
            print(f"Adding {len(SAMPLE_TRADES)} sample trades...")
            for trade_data in SAMPLE_TRADES:
                t = schemas.TradeCreate(**trade_data)
                crud.create_trade(db, t)
            print(f"Added {len(SAMPLE_TRADES)} trades.")
        else:
            print(f"Database already has {trade_count} trades. Skipping trade insert.")

        planned_count = db.query(models.PlannedTrade).count()
        if planned_count == 0:
            print(f"Adding {len(SAMPLE_PLANNED)} planned trades and tests...")
            for pt_data in SAMPLE_PLANNED:
                tests = pt_data.pop("tests", [])
                pt_schema = schemas.PlannedTradeCreate(**pt_data)
                pt = crud.create_planned_trade(db, pt_schema)

                for test_data in tests:
                    lt_schema = schemas.LevelTestCreate(
                        planned_trade_id=pt.id,
                        **test_data,
                    )
                    crud.create_level_test(db, lt_schema)
            print(f"Added {len(SAMPLE_PLANNED)} planned trades.")
        else:
            print(f"Database already has {planned_count} planned trades. Skipping planned insert.")

        print("\n=== Seed verification ===")
        kpi = crud.get_dashboard_kpi(db)
        print(f"Total Trades: {kpi.total_trades}")
        print(f"Wins: {kpi.wins}, Losses: {kpi.losses}, BE: {kpi.breakeven}")
        print(f"Win Rate: {kpi.win_rate}%")
        print(f"Total PnL: ${kpi.total_pnl}")
        print(f"Profit Factor: {kpi.profit_factor}")
        print(f"Avg R: {kpi.avg_r}")
        print("Seed completed successfully!")


if __name__ == "__main__":
    run_seed()
